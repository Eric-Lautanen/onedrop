"""Render the whole audio engine to WAV files, offline.

Run: dev/.venv-playfield/Scripts/python.exe dev/render-audio.py

Every cue and every song is rendered through an OfflineAudioContext in the
page -- the same code the game plays -- and posted back to a tiny local
sink, so the results can be listened to (dev/audio/) and measured with the
standard library (peak, RMS, band energy, duration). No audio files are
generated by the game itself: this is an instrument for tuning the
synthesised kit, not part of the game.

The offline context is the point: it renders faster than real time, with no
scheduler jitter and no need for a user gesture, so a measurement is
reproducible.
"""
import base64
import json
import math
import re
import struct
import threading
import wave
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import unquote

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent
OUT = ROOT / 'audio'
PORT = 8123

SFX = ['flipper', 'flipperReturn', 'bumper', 'sling', 'bash', 'post', 'target', 'standup',
       'rollover', 'spinner', 'drain', 'rampup', 'ramp', 'launch', 'kickback', 'ballsave',
       'multiball', 'jackpot', 'bonus', 'tilt', 'start', 'gameover', 'charge', 'nudge', 'coin']


# ---------------------------------------------------------------- sink
def slugify(name):
    """A section called `chant 2` is a fine name and a bad filename: the
    space comes back percent-encoded in the URL, the sink stores it under a
    different key, and the render writes a zero-byte WAV that only fails
    later, in the wave reader. Everything on disk is slugged."""
    return re.sub(r'[^A-Za-z0-9._-]+', '-', str(name)).strip('-')


class Sink(BaseHTTPRequestHandler):
    files = {}

    def do_POST(self):
        name = unquote(self.path.split('name=', 1)[-1]) or 'x.wav'
        n = int(self.headers.get('Content-Length', 0))
        body = self.rfile.read(n)
        try:
            Sink.files[name] = base64.b64decode(body)
            code = 204
        except Exception as exc:                      # noqa: BLE001 - reported below
            Sink.files[name] = b''
            Sink.error = str(exc)
            code = 500
        self.send_response(code)
        self.send_header('Access-Control-Allow-Origin', '*')
        self.send_header('Content-Length', '0')
        self.end_headers()

    def do_OPTIONS(self):
        self.send_response(204)
        self.send_header('Access-Control-Allow-Origin', '*')
        self.send_header('Access-Control-Allow-Headers', '*')
        self.end_headers()

    def log_message(self, *a):
        pass


def start_sink():
    srv = ThreadingHTTPServer(('127.0.0.1', PORT), Sink)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv


# ------------------------------------------------------------- renderer
RENDER = r"""
() => {
  window.__render = async (kind, arg, secs) => {
    const SR = 48000;
    const oac = new OfflineAudioContext(2, Math.ceil(SR * secs), SR);
    const Real = window.AudioContext;
    window.AudioContext = function () { return oac; };
    const e = new PB.AudioEngine();
    try {
      e.init();
      if (kind === 'charge') {
        e.chargeLevel(0.85);
      } else if (kind === 'sfx') {
        e.sfx(arg, 2, 0);
      } else if (kind === 'insert') {
        const ins = PB.AudioEngine.INSERTS[arg];
        const n = Math.min(ins.run, Math.round(secs / ins.stepDur) - 2);
        for (let i = 0; i < n; i++) e._scheduleSongStep(ins, i, 0.1 + i * ins.stepDur);
      } else if (kind === 'section') {
        /* one section of a song on its own, so the arrangement can be heard
           (and measured) side by side without waiting out the whole song */
        const song = PB.AudioEngine.SONGS[arg[0]];
        const secLen = (song.secBars || 4) * 16;
        const n = Math.round(secs / song.stepDur) - 2;
        for (let i = 0; i < n; i++) e._scheduleSongStep(song, arg[1] * secLen + i, 0.1 + i * song.stepDur);
      } else {
        const song = PB.AudioEngine.SONGS[arg];
        e._songIdx = arg;
        const n = Math.min(song.run, Math.round(secs / song.stepDur) - 2);
        for (let i = 0; i < n; i++) e._scheduleSongStep(song, i, 0.1 + i * song.stepDur);
      }
    } finally {
      window.AudioContext = Real;
      if (e._rollTimer) clearInterval(e._rollTimer);
      if (e._timer) clearInterval(e._timer);
    }
    const buf = await oac.startRendering();
    return buf;
  };

  window.__wav = (buf) => {
    const ch = buf.numberOfChannels, len = buf.length, rate = buf.sampleRate;
    const bytes = new Uint8Array(44 + len * ch * 2);
    const dv = new DataView(bytes.buffer);
    const str = (o, s) => { for (let i = 0; i < s.length; i++) dv.setUint8(o + i, s.charCodeAt(i)); };
    str(0, 'RIFF'); dv.setUint32(4, 36 + len * ch * 2, true); str(8, 'WAVE');
    str(12, 'fmt '); dv.setUint32(16, 16, true); dv.setUint16(20, 1, true); dv.setUint16(22, ch, true);
    dv.setUint32(24, rate, true); dv.setUint32(28, rate * ch * 2, true);
    dv.setUint16(32, ch * 2, true); dv.setUint16(34, 16, true);
    str(36, 'data'); dv.setUint32(40, len * ch * 2, true);
    const chans = [];
    for (let c = 0; c < ch; c++) chans.push(buf.getChannelData(c));
    let o = 44;
    for (let i = 0; i < len; i++) {
      for (let c = 0; c < ch; c++) {
        let s = Math.max(-1, Math.min(1, chans[c][i]));
        dv.setInt16(o, s < 0 ? s * 0x8000 : s * 0x7fff, true);
        o += 2;
      }
    }
    return bytes;
  };

  window.__b64 = (bytes) => {
    let s = '';
    const CH = 0x8000;
    for (let i = 0; i < bytes.length; i += CH) {
      s += String.fromCharCode.apply(null, bytes.subarray(i, i + CH));
    }
    return btoa(s);
  };

  window.__save = (name, b64) => fetch('http://127.0.0.1:PORT/save?name=' + name, {
    method: 'POST',
    headers: { 'Content-Type': 'text/plain' },
    body: b64
  }).then(r => r.status);
  return 'ready';
}
""".replace('PORT', str(PORT))


# ---------------------------------------------------------- measurement
def read_wav(path):
    with wave.open(str(path), 'rb') as w:
        ch, sw, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    assert sw == 2, 'expected 16-bit'
    data = struct.unpack('<%dh' % (len(raw) // 2), raw)
    mono = []
    for i in range(0, len(data) - ch + 1, ch):
        mono.append(sum(data[i:i + ch]) / (ch * 32768.0))
    return rate, mono


def band_energy(mono, rate, freq):
    """One Goertzel bin: how much of this signal is at `freq`."""
    w = 2 * math.pi * freq / rate
    c = 2 * math.cos(w)
    s0 = s1 = s2 = 0.0
    step = max(1, len(mono) // 120000)          # keep the transform quick
    n = 0
    for i in range(0, len(mono), step):
        s0 = mono[i] + c * s1 - s2
        s2, s1 = s1, s0
        n += 1
    p = s1 * s1 + s2 * s2 - c * s1 * s2
    return math.sqrt(max(0.0, p)) / max(1, n)


def window_profile(mono, rate):
    """How the cue behaves over time: the peak and the high/low ratio in
    five slices. A mechanical cue needs a bright attack that decays into
    a low body; this is the number that says whether it has one."""
    slices = [(0.0, 0.015), (0.015, 0.045), (0.045, 0.10), (0.10, 0.30), (0.30, 2.0)]
    out = []
    for a, b in slices:
        seg = mono[int(a * rate):int(b * rate)]
        if len(seg) < 32:
            out.append(None)
            continue
        pk = max(abs(v) for v in seg)
        hi = band_energy(seg, rate, 3200)
        lo = band_energy(seg, rate, 140)
        ratio = 20 * math.log10((hi + 1e-9) / (lo + 1e-9))
        out.append({'at': a, 'peakDb': round(20 * math.log10(max(pk, 1e-9)), 1),
                    'hiLoDb': round(max(-40.0, min(40.0, ratio)), 1)})
    return out


def measure(path):
    rate, mono = read_wav(path)
    if not mono:
        return {'error': 'empty'}
    peak = max(abs(v) for v in mono)
    rms = math.sqrt(sum(v * v for v in mono) / len(mono))
    # duration above -60 dBFS
    thr = 10 ** (-60 / 20)
    last = 0
    for i, v in enumerate(mono):
        if abs(v) > thr:
            last = i
    tail = round(last / rate, 3)
    zc = 0
    for i in range(1, len(mono)):
        if (mono[i - 1] < 0) != (mono[i] < 0):
            zc += 1
    bands = {str(f): round(band_energy(mono, rate, f), 6) for f in (60, 120, 250, 500, 1000, 2000, 4000, 8000)}
    low = bands['60'] + bands['120'] + bands['250']
    mid = bands['500'] + bands['1000']
    high = bands['2000'] + bands['4000'] + bands['8000']
    tot = low + mid + high or 1e-9
    return {
        'seconds': round(len(mono) / rate, 3),
        'peak': round(peak, 4),
        'peakDb': round(20 * math.log10(max(peak, 1e-9)), 2),
        'rms': round(rms, 4),
        'rmsDb': round(20 * math.log10(max(rms, 1e-9)), 2),
        'soundingSeconds': tail,
        'zeroCrossRate': zc / (len(mono) / rate),
        'bands': bands,
        'balance': {'low': round(low / tot, 3), 'mid': round(mid / tot, 3), 'high': round(high / tot, 3)},
        'profile': window_profile(mono, rate),
    }


def main():
    OUT.mkdir(exist_ok=True)
    # A re-render must leave the folder matching the report: an edited set list
    # renames and drops files, and last night's `song-3.wav` sitting next to a
    # fresh `song-3.wav` is worse than no file at all. This folder is
    # generated output -- nothing here is hand-made.
    stale = sorted(OUT.glob('*.wav'))
    for f in stale:
        f.unlink()
    if stale:
        print('cleared %d stale wav(s) from %s' % (len(stale), OUT))
    start_sink()
    report = {'sfx': {}, 'songs': {}, 'inserts': {}}
    with sync_playwright() as p:
        browser = p.chromium.launch(channel='msedge', args=[
            '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader',
            '--autoplay-policy=no-user-gesture-required'])
        page = browser.new_page(viewport={'width': 900, 'height': 700})
        errors = []
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.goto('http://127.0.0.1:8101/', wait_until='load')
        page.wait_for_function('window.PB && PB.game && PB.assets.ready', timeout=60000)
        page.evaluate(RENDER)

        # a job carries its own label: the label used to be guessed back out
        # of the filename afterwards, which is how two songs with a section
        # called `break` ended up reported under the one name and one of them
        # quietly vanished from the report
        jobs = [('sfx', n, 1.6, 'sfx-' + n + '.wav', n) for n in SFX if n != 'charge']
        jobs.append(('charge', 'charge', 0.5, 'sfx-charge.wav', 'charge'))
        songs = page.evaluate('''PB.AudioEngine.SONGS.map(s => ({name: s.name, bpm: s.bpm, run: s.run,
          secBars: s.secBars, stepDur: 60 / s.bpm / 4,
          flags: s.arrange ? s.arrange.map(x => ({name: x.name, w: [x.d,x.k,x.o,x.b,x.l,x.x,x.p].filter(Boolean).length})) : []}))''')
        for i, s in enumerate(songs):
            secs = min(26.0, s['run'] * s['stepDur'] + 1.0)
            slug = s['name'].lower().replace(' ', '-')
            jobs.append(('song', i, secs, 'song-%d.wav' % i, 'song %s' % slug))
            # The BREAK and the busiest section of each song, chosen the same
            # way the suite chooses them (by name for the break, by layer count
            # for the peak), so the wavs on disk are the two sections the
            # arrangement check is about. One section's worth of steps plus a
            # tail, so the render is exactly that section and nothing of the
            # next one.
            if s['flags']:
                brk = [j for j, f in enumerate(s['flags']) if f['name'] == 'break']
                brk = brk[0] if brk else min(range(len(s['flags'])), key=lambda j: s['flags'][j]['w'])
                hi = max(range(len(s['flags'])), key=lambda j: s['flags'][j]['w'])
                secLen = s['secBars'] * 16
                secs2 = round(secLen * s['stepDur'] + 1.5, 2)
                for kind, j in (('break', brk), ('peak', hi)):
                    fname = slugify('song-%d-%s-%s.wav' % (i, kind, s['flags'][j]['name']))
                    label = fname[:-4]      # the report key IS the file name, so the two
                                            # cannot drift apart
                    jobs.append(('section', (i, j), secs2, fname, label))
        inserts = page.evaluate('PB.AudioEngine.INSERTS.map(s => ({name: s.name, bpm: s.bpm, run: s.run, stepDur: 60 / s.bpm / 4}))')
        for i, s in enumerate(inserts):
            slug = s['name'].lower().replace(' ', '-')
            jobs.append(('insert', i, min(22.0, s['run'] * s['stepDur'] + 1.0),
                         'insert-%s.wav' % slug, 'insert-%s' % slug))

        for kind, arg, secs, name, label in jobs:
            path = OUT / name
            buf = page.evaluate_handle('([k,a,s]) => window.__render(k,a,s)', [kind, arg, secs])
            page.evaluate('(b) => window.__save(NAME, window.__b64(window.__wav(b)))'.replace('NAME', repr(name)),
                          buf)
            buf.dispose()
            raw = Sink.files.get(name, b'')
            if len(raw) <= 44:            # a header and nothing else: say so here, loudly,
                raise RuntimeError(       # rather than weeks later in the wave reader
                    'render %r posted %d bytes -- the sink never got it (name=%r)'
                    % (name, len(raw), name))
            path.write_bytes(raw)
            m = measure(path)
            m['job'] = label
            bucket = 'sfx' if kind in ('sfx', 'charge') else ('inserts' if kind == 'insert' else 'songs')
            report[bucket][label] = m
            atk = (m.get('profile') or [{}])[0] or {}
            print('%-14s peak %6.2f dB   rms %6.2f dB   %5.2fs  hi/lo@%dms %6.1f dB' % (
                label, m.get('peakDb', -99), m.get('rmsDb', -99),
                m.get('soundingSeconds', 0), int(atk.get('at', 0) * 1000),
                atk.get('hiLoDb', -99)))
        report['songsMeta'] = songs
        report['errors'] = errors
        browser.close()

    (ROOT / 'audio-render.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    print('\nwrote', OUT, 'and audio-render.json')


if __name__ == '__main__':
    main()
